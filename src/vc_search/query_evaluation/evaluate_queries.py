# Добавляем путь к модулю vc_search
sys.path.append(os.path.join(os.path.dirname(__file__), ".."))

from vc_search.search.elastic_client import VCElasticSearch
import csv


class QueryEvaluator:
    def __init__(self):
        self.es = VCElasticSearch()

    def clean_content(self, content, max_length=32000):
        """Убирает переносы строк из контента и ограничивает длину"""
        if not content:
            return ""
        # Заменяем все виды переносов строк пробелами и убираем лишние пробелы
        cleaned = content.replace("\n", " ").replace("\r", " ").replace("\t", " ")
        # Убираем множественные пробелы
        normalized = " ".join(cleaned.split())

        # Ограничиваем длину для CSV совместимости
        if len(normalized) > max_length:
            return normalized[:max_length] + "... [текст обрезан]"
        return normalized

    def search_queries(self, queries, results_per_query=10, output_file=None):
        """Ищет результаты для списка запросов используя improved_search и сохраняет в CSV"""
        if not output_file:
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            output_file = f"search_results_{timestamp}.csv"

        all_results = []

        for query in queries:
            print(f"🔍 Searching: '{query}'")

            try:
                # Используем improved_search из VCElasticSearch
                search_results = self.es.search(query, limit=results_per_query)

                for i, result in enumerate(search_results["results"]):
                    # Получаем полный контент статьи по ID
                    full_content = self.get_full_article_content_by_id(
                        result.get("id", "")
                    )

                    # Если не нашли по ID, пробуем получить контент из превью
                    if not full_content:
                        full_content = result.get("content", "")

                    result_data = {
                        "relevance_score": "",  # для ручной разметки
                        "query": query,
                        "article_title": self.clean_content(result.get("title", "")),
                        "article_category": result.get("section", ""),
                        "article_content": self.clean_content(
                            full_content
                        ),  # последний столбец
                    }
                    all_results.append(result_data)

                print(f"✅ Found {len(search_results['results'])} results")

            except Exception as e:
                print(f"❌ Error for query '{query}': {e}")
                continue

        # Сохраняем в CSV
        self._save_to_csv(all_results, output_file)
        return output_file

    def get_full_article_content_by_id(self, article_id):
        """Получает полный контент статьи по ID из Elasticsearch"""
        try:
            # Получаем документ по ID
            response = self.es.client.get(index=self.es.index_name, id=article_id)

            if response["found"]:
                full_content = response["_source"].get("content", "")
                print(
                    f"📄 Получен контент длиной {len(full_content)} символов (ID: {article_id})"
                )
                return full_content
            else:
                print(f"⚠️ Статья не найдена по ID: {article_id}")
                return ""

        except Exception as e:
            print(f"⚠️ Could not fetch content by ID {article_id}: {e}")
            return ""

    def _save_to_csv(self, results, output_file):
        """Сохраняет результаты в CSV файл"""
        if not results:
            print("❌ No results to save")
            return

        # Столбцы в нужном порядке - article_content последний
        fieldnames = [
            "relevance_score",
            "query",
            "article_title",
            "article_category",
            "article_content",  # последний столбец
        ]

        try:
            with open(output_file, "w", newline="", encoding="utf-8") as csvfile:
                writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
                writer.writeheader()

                for result in results:
                    # Проверяем длину каждого поля перед записью
                    cleaned_result = {}
                    for key, value in result.items():
                        if isinstance(value, str):
                            # Дополнительная очистка для CSV
                            cleaned_value = value.replace('"', "'").replace(";", ",")
                            cleaned_result[key] = cleaned_value
                        else:
                            cleaned_result[key] = value

                    writer.writerow(cleaned_result)

            print(f"💾 Results saved to: {output_file}")
            print(f"📊 Total records: {len(results)}")

            # Проверяем, есть ли контент в сохраненных данных
            content_stats = self._check_content_stats(results)
            print(f"📝 Content statistics: {content_stats}")

        except Exception as e:
            print(f"❌ Error saving CSV: {e}")
            # Пробуем сохранить без проблемных строк
            self._save_fallback(results, output_file)

    def _check_content_stats(self, results):
        """Проверяет статистику по контенту"""
        total = len(results)
        with_content = 0
        content_lengths = []

        for result in results:
            content = result.get("article_content", "")
            if content and len(content.strip()) > 10:
                with_content += 1
                content_lengths.append(len(content))

        stats = {
            "total_articles": total,
            "articles_with_content": with_content,
            "avg_content_length": sum(content_lengths) // len(content_lengths)
            if content_lengths
            else 0,
        }
        return stats

    def _save_fallback(self, results, output_file):
        """Альтернативный метод сохранения если основной не работает"""
        try:
            with open(output_file, "w", newline="", encoding="utf-8") as csvfile:
                writer = csv.DictWriter(
                    csvfile,
                    fieldnames=[
                        "relevance_score",
                        "query",
                        "article_title",
                        "article_category",
                        "article_content",
                    ],
                )
                writer.writeheader()

                for i, result in enumerate(results):
                    try:
                        writer.writerow(result)
                    except Exception as row_error:
                        print(f"⚠️ Skipping row {i} due to error: {row_error}")
                        continue

            print(f"💾 Results saved (fallback method): {output_file}")

        except Exception as e:
            print(f"❌ Critical error saving CSV: {e}")


